#!/usr/bin/env python3
"""Compact consistency checks for the creative surface compiler."""

from __future__ import annotations

import csv
import json
import subprocess
import sys
from collections import Counter
from pathlib import Path


HERE = Path(__file__).resolve().parent


def read_tsv(name: str) -> list[dict[str, str]]:
    with (HERE / name).open(encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle, delimiter="\t"))


def main() -> int:
    checks: list[dict[str, object]] = []

    def check(name: str, condition: bool, detail: object) -> None:
        checks.append({"check": name, "pass": bool(condition), "detail": detail})

    rules = read_tsv("SURFACE_COMPILER_RULES.tsv")
    surfaces = read_tsv("COMPLETE_230_SURFACE_PARSE.tsv")
    cards = read_tsv("COMPLETE_173_LITERAL_PARSE.tsv")
    paradigms = read_tsv("PRODUCTIVE_PARADIGMS.tsv")
    predictions = read_tsv("FORWARD_PREDICTIONS.tsv")
    corrections = read_tsv("BRIDGE_ROOT_CORRECTIONS.tsv")
    summary = json.loads((HERE / "BUILD_SUMMARY.json").read_text(encoding="utf-8"))

    check("rule_count", len(rules) == 29, len(rules))
    check("surface_count", len(surfaces) == 230, len(surfaces))
    check("surface_unique", len({row["visible_surface"] for row in surfaces}) == 230, "230 expected")
    check("card_count", len(cards) == 173, len(cards))
    check("card_unique", len({row["master_card_id"] for row in cards}) == 173, "173 expected")
    check("event_sum", sum(int(row["prose_events"]) for row in cards) == 381, sum(int(row["prose_events"]) for row in cards))
    check("prediction_count", len(predictions) == 18, len(predictions))
    check("correction_count", len(corrections) == 8, len(corrections))
    check("dch_withdrawn", corrections[0]["new_status"] == "WITHDRAW_AS_STEM", corrections[0]["new_status"])
    check("dchol_whole", next(row for row in cards if row["master_head_form"] == "dchol")["corrected_semantic_atoms"] == "DCHOL", "DCHOL")
    check("no_free_dch_atom", all("DCH" not in row["corrected_semantic_atoms"].split("+") for row in cards), "DCH absent")
    check("chd_retained", sum("CHD" in row["corrected_semantic_atoms"].split("+") for row in cards) >= 10, "CHD family")
    check("all_surface_meanings", all(row["short_default_de"].strip() for row in surfaces), "nonempty")
    check("all_card_rules", all(row["forward_reading_rule"].strip() for row in cards), "nonempty")
    check("all_prediction_glosses", all(row["predicted_short_reading_de"].strip() for row in predictions), "nonempty")
    check("ho_ar_collision_visible", any(row["predicted_atom_sequence"] == "HO+AR" and "kchoar" in row["loose_surface_hits_in_230"] for row in predictions), "kchoar guarded")
    check("summary_counts", summary["dictionary_cards"] == 173 and summary["surface_forms"] == 230 and summary["prose_events"] == 381 and summary["statements"] == 116, summary)
    check("literal_cue_cards", summary["cards_with_literal_predictive_atom"] == 163, summary["cards_with_literal_predictive_atom"])
    check("paradigms_present", len(paradigms) >= 12, len(paradigms))
    check("no_sealed_pages", all("f84" not in "\t".join(row.values()).lower() for table in (surfaces, cards, paradigms, predictions) for row in table), "sealed tokens absent")

    # Deterministic rebuild: generated bytes must remain identical.
    products = [
        "SURFACE_COMPILER_RULES.tsv", "COMPLETE_230_SURFACE_PARSE.tsv",
        "COMPLETE_173_LITERAL_PARSE.tsv", "PRODUCTIVE_PARADIGMS.tsv",
        "FORWARD_PREDICTIONS.tsv", "BRIDGE_ROOT_CORRECTIONS.tsv",
        "SURFACE_COMPILER_REPORT.md", "BUILD_SUMMARY.json",
    ]
    before = {name: (HERE / name).read_bytes() for name in products}
    subprocess.run([sys.executable, str(HERE / "build_surface_compiler.py")], check=True, cwd=HERE.parents[3])
    after = {name: (HERE / name).read_bytes() for name in products}
    check("deterministic_rebuild", before == after, "all generated bytes identical")

    counts = Counter("PASS" if item["pass"] else "FAIL" for item in checks)
    result = {
        "status": "PASS" if not counts["FAIL"] else "FAIL",
        "checks": checks,
        "pass_count": counts["PASS"],
        "fail_count": counts["FAIL"],
    }
    (HERE / "VALIDATION.json").write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{result['status']}: {counts['PASS']}/{len(checks)} checks")
    return 0 if result["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
